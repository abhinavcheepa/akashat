"""Question entity and offline QuestionManager for PATHFINDER.

Manages categorized quiz items across DSA, Python, DBMS, OS, Networks, Math,
and General Knowledge, plus custom study materials generated by RAG.
Includes anti-repetition randomization, graceful fallbacks for scarce pools,
and verified answer keys.
"""

from collections import deque
import json
import os
import random
from typing import Any, Deque, Dict, List, Optional, Set


class Question:
    """Represents a multiple-choice question item for checkpoint gates.

    Attributes:
        id: Unique identifier string.
        topic: Knowledge area (e.g., 'DSA', 'Python and OOP', 'Custom Materials').
        difficulty: 'Easy', 'Medium', or 'Hard'.
        question: Question stem text.
        options: Exactly 4 distinct answer choices.
        answer: 0-indexed integer of the correct option.
        explanation: Technical rationale explaining the answer.
    """

    def __init__(
        self,
        id: str,
        topic: str,
        difficulty: str,
        question: str,
        options: List[str],
        answer: int,
        explanation: str,
    ) -> None:
        self.id: str = id
        self.topic: str = topic
        self.difficulty: str = difficulty
        self.question: str = question
        self.options: List[str] = list(options)
        self.answer: int = int(answer)
        self.explanation: str = explanation

    def is_correct(self, option_index: int) -> bool:
        """Verify whether the selected option matches the answer index."""
        return option_index == self.answer

    @property
    def answer_text(self) -> str:
        """Return the text of the correct answer choice."""
        if 0 <= self.answer < len(self.options):
            return self.options[self.answer]
        return ""

    def create_shuffled_copy(self) -> "Question":
        """Return a copy with options randomized and answer index updated.

        Guarantees questions do not always place the correct answer in the same letter slot.
        """
        correct_text = self.options[self.answer]
        indexed_options = list(enumerate(self.options))
        random.shuffle(indexed_options)

        shuffled_options = [opt for _, opt in indexed_options]
        new_answer_idx = shuffled_options.index(correct_text)

        return Question(
            id=self.id,
            topic=self.topic,
            difficulty=self.difficulty,
            question=self.question,
            options=shuffled_options,
            answer=new_answer_idx,
            explanation=self.explanation,
        )


class QuestionManager:
    """Loads, validates, and dispenses questions with strict anti-repetition guards and graceful fallbacks."""

    def __init__(self, data_path: str = "data/questions.json", history_capacity: int = 15) -> None:
        """Initialize QuestionManager and load offline question catalog."""
        self.data_path: str = data_path
        self.questions: List[Question] = []
        self.by_topic: Dict[str, List[Question]] = {}
        self.custom_materials: List[Question] = []
        self.recent_ids: Deque[str] = deque(maxlen=history_capacity)

        self.load()

    def load(self) -> bool:
        """Load and parse question bank from disk."""
        if not os.path.exists(self.data_path):
            return False

        try:
            with open(self.data_path, "r", encoding="utf-8") as f:
                data = json.load(f)

            raw_questions = data.get("questions", [])

            loaded: List[Question] = []
            topic_map: Dict[str, List[Question]] = {}

            for item in raw_questions:
                q = Question(
                    id=item.get("id", f"q_{len(loaded)}"),
                    topic=item.get("topic", "General Knowledge"),
                    difficulty=item.get("difficulty", "Easy"),
                    question=item.get("question", ""),
                    options=item.get("options", ["A", "B", "C", "D"]),
                    answer=item.get("answer", 0),
                    explanation=item.get("explanation", ""),
                )
                loaded.append(q)
                topic_map.setdefault(q.topic, []).append(q)

            self.questions = loaded
            self.by_topic = topic_map
            return len(self.questions) > 0

        except Exception as e:
            print(f"[Warning] Failed loading questions bank: {e}")
            return False

    def add_custom_questions(self, questions: List[Question]) -> None:
        """Add custom study questions generated by RAG pipeline."""
        self.custom_materials = list(questions)
        self.by_topic["Custom Materials"] = self.custom_materials
        # Also include them in global pool
        self.questions = [q for q in self.questions if q.topic != "Custom Materials"] + self.custom_materials

    def clear_custom_questions(self) -> None:
        """Remove custom questions from manager."""
        self.custom_materials.clear()
        self.by_topic.pop("Custom Materials", None)
        self.questions = [q for q in self.questions if q.topic != "Custom Materials"]

    def has_custom_materials(self) -> bool:
        """Return True if custom study material questions are loaded."""
        return len(self.custom_materials) > 0

    def get_topics(self) -> List[str]:
        """Return list of distinct loaded question topics.

        Only includes 'Custom Materials' if custom material questions exist.
        """
        topics = [t for t in self.by_topic.keys() if t != "Custom Materials"]
        if self.has_custom_materials():
            topics.append("Custom Materials")
        return topics

    def get_question(
        self,
        topic: Optional[str] = None,
        difficulty: Optional[str] = None,
        exclude_ids: Optional[Set[str]] = None,
        shuffle_options: bool = True,
    ) -> Optional[Question]:
        """Dispense a randomized question matching criteria without immediate repeat.

        Gracefully degrades criteria if a topic or difficulty has scarce questions,
        guaranteeing the game never crashes or fails to serve a valid question.

        Args:
            topic: Filter by specific category (or None / 'All Topics' for any).
            difficulty: Filter by 'Easy', 'Medium', 'Hard' (or None / 'Level Default' for any).
            exclude_ids: Optional set of question IDs currently active in session.
            shuffle_options: Whether to randomize option order before returning.

        Returns:
            A Question instance, or None if the bank is completely empty.
        """
        if not self.questions:
            return None

        # 1. Pool selection based on topic with graceful fallback to all questions
        if topic and topic != "All Topics" and topic in self.by_topic and self.by_topic[topic]:
            pool = list(self.by_topic[topic])
        else:
            pool = list(self.questions)

        # 2. Filter by difficulty if requested and available, else fall back gracefully
        if difficulty and difficulty != "Level Default":
            diff_pool = [q for q in pool if q.difficulty.lower() == difficulty.lower()]
            if diff_pool:
                pool = diff_pool
            elif not topic or topic == "All Topics":
                # Only fall back to global difficulty pool if topic was not strictly specified
                global_diff_pool = [q for q in self.questions if q.difficulty.lower() == difficulty.lower()]
                if global_diff_pool:
                    pool = global_diff_pool
            # If a specific topic was requested (e.g. Custom Materials), preserve the topic pool even if difficulty differs

        # 3. Filter out currently excluded and recently served IDs
        combined_exclude = set(self.recent_ids)
        if exclude_ids:
            combined_exclude.update(exclude_ids)

        eligible = [q for q in pool if q.id not in combined_exclude]

        if not eligible:
            eligible = [q for q in pool if not (exclude_ids and q.id in exclude_ids)]

        if not eligible:
            eligible = self.questions

        chosen = random.choice(eligible)
        self.record_served(chosen.id)

        if shuffle_options:
            return chosen.create_shuffled_copy()
        return chosen

    def record_served(self, question_id: str) -> None:
        """Record question ID in anti-repetition memory."""
        self.recent_ids.append(question_id)

    def reset_history(self) -> None:
        """Clear recent anti-repetition history."""
        self.recent_ids.clear()
